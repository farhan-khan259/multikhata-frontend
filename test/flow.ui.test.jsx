import React from 'react';
import 'fake-indexeddb/auto';
import {it,expect} from 'vitest';
import {render,screen,waitFor,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from '../src/App';
HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','')};
it('reference-style party flow keeps PKR only and offline entry add/edit/delete',async()=>{
 const user=userEvent.setup();render(<App/>);
 expect(screen.queryByRole('button',{name:'Create account'})).toBeNull();
 await user.click(screen.getByRole('button',{name:/Explore sample khata/}));
 await screen.findByRole('heading',{name:/Your khata, at a glance/});
 expect(screen.getByText('Pakistani Rupee')).toBeTruthy();expect(screen.queryByText('Chinese Yuan')).toBeNull();
 await user.click(screen.getByRole('button',{name:'Party khata'}));
 await user.click(screen.getByRole('button',{name:'ADD CUSTOMER'}));
 let dialog=screen.getByRole('dialog');await user.type(within(dialog).getByLabelText('Party name'),'Test Offline Party');
 await user.click(within(dialog).getByRole('button',{name:'Save party'}));
 await screen.findByRole('heading',{name:'Test Offline Party'});
 await user.click(screen.getByRole('button',{name:'Open khata for Test Offline Party'}));
 expect(screen.getByLabelText('Ledger currency').disabled).toBe(true);
 await user.click(screen.getByRole('button',{name:'YOU GAVE PKR'}));
 dialog=screen.getByRole('dialog');expect(within(dialog).getByLabelText('Currency').value).toBe('PKR');
 await user.type(within(dialog).getByLabelText('Amount'),'10000 × 42');
 expect(within(dialog).queryByLabelText('Rate in PKR')).toBeNull();
 expect(within(dialog).getByText('= PKR 420,000.00')).toBeTruthy();
 await user.type(within(dialog).getByLabelText(/Note/),'Offline UI test entry');
 await user.click(within(dialog).getByRole('button',{name:'Save entry'}));await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull());
 await screen.findByText('Offline UI test entry');
 let row=screen.getByText('Offline UI test entry').closest('.ledger-entry');expect(within(row).getByText('PKR 420,000.00')).toBeTruthy();
 expect(within(row).getByText(/10000 × 42 = PKR 420,000.00/)).toBeTruthy();
 expect(screen.getByText('PKR 420,000.00',{selector:'.ledger-summary strong'})).toBeTruthy();
 expect(screen.getByRole('button',{name:'Report Excel'})).toBeTruthy();
 await user.click(within(row).getByRole('button',{name:/Edit entry/}));
 dialog=screen.getByRole('dialog');await user.clear(within(dialog).getByLabelText('Amount'));await user.type(within(dialog).getByLabelText('Amount'),'150.50');await user.click(within(dialog).getByRole('button',{name:'Save entry'}));await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull());
 await waitFor(()=>expect(within(screen.getByText('Offline UI test entry').closest('.ledger-entry')).getByText('PKR 150.50')).toBeTruthy());
 expect(screen.getByText('PKR 150.50',{selector:'.ledger-summary strong'})).toBeTruthy();
 expect(screen.getByLabelText('Ledger currency').options.length).toBe(1);
 expect(screen.getByLabelText('Ledger currency').disabled).toBe(true);
 row=screen.getByText('Offline UI test entry').closest('.ledger-entry');await user.click(within(row).getByRole('button',{name:'Delete entry'}));
 await user.click(within(screen.getByRole('dialog')).getByRole('button',{name:'Delete entry'}));
 await waitFor(()=>expect(screen.queryByText('Offline UI test entry')).toBeNull());
 await user.click(screen.getByRole('button',{name:/Sync & backup/}));
 expect(await screen.findByRole('heading',{name:/Your changes are ready to sync/})).toBeTruthy();
 expect(screen.getAllByRole('button',{name:'Sync now',exact:true}).every(b=>b.disabled)).toBe(true);
});
